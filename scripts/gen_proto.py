#!/usr/bin/env python3
"""Regenerate the nanopb sources for the ESPHome native API.

Inputs:  proto/api.proto, proto/api_options.proto (from aioesphomeapi)
Outputs: src/esphome/api.pb.c, include/esphome/api.pb.h, include/esphome/api_ids.h

Requires the nanopb generator (pip install nanopb==0.4.9.1 grpcio-tools),
matching third_party/nanopb. Usage: scripts/gen_proto.py [nanopb_generator]
"""
import os
import re
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PROTO = os.path.join(ROOT, "proto", "api.proto")
GEN = sys.argv[1] if len(sys.argv) > 1 else "nanopb_generator"

text = open(PROTO).read()

# Every string, bytes and repeated field becomes a heap pointer (FT_POINTER,
# PB_ENABLE_MALLOC) so the ~240 messages don't each carry fixed-size buffers.
options = []
ids = []
for m in re.finditer(r"^message (\w+) \{(.*?)^\}", text, re.S | re.M):
    name, body = m.group(1), m.group(2)
    for f in re.finditer(r"^\s*(repeated\s+)?([\w.]+)\s+(\w+)\s*=\s*\d+", body, re.M):
        repeated, ftype, fname = f.groups()
        if repeated or ftype in ("string", "bytes"):
            options.append(f"{name}.{fname} type:FT_POINTER")
    mid = re.search(r"option \(id\) = (\d+);", body)
    if mid:
        ids.append((name, int(mid.group(1))))

with tempfile.TemporaryDirectory() as tmp:
    with open(os.path.join(tmp, "api.options"), "w") as f:
        f.write("\n".join(options) + "\n")
    subprocess.check_call([
        GEN, "-I", os.path.join(ROOT, "proto"), "-f", os.path.join(tmp, "api.options"),
        "-D", tmp, "api.proto",
    ], cwd=os.path.join(ROOT, "proto"))
    src = open(os.path.join(tmp, "api.pb.c")).read()
    hdr = open(os.path.join(tmp, "api.pb.h")).read()

# api.pb.h includes api_options.pb.h for the custom options; nothing in
# the generated code uses them.
hdr = hdr.replace('#include "api_options.pb.h"\n', "")
os.makedirs(os.path.join(ROOT, "include", "esphome"), exist_ok=True)
os.makedirs(os.path.join(ROOT, "src", "esphome"), exist_ok=True)
open(os.path.join(ROOT, "include", "esphome", "api.pb.h"), "w").write(hdr)
open(os.path.join(ROOT, "src", "esphome", "api.pb.c"), "w").write(src)


def snake(n):
    return re.sub(r"(?<!^)(?=[A-Z])", "_", n).upper()


with open(os.path.join(ROOT, "include", "esphome", "api_ids.h"), "w") as f:
    f.write("/* Generated by scripts/gen_proto.py from proto/api.proto. Do not edit. */\n")
    f.write("#pragma once\n\n")
    f.write("enum ApiMessageId {\n")
    for name, mid in ids:
        f.write(f"  MSG_{snake(name)} = {mid},\n")
    f.write("};\n")

print(f"{len(ids)} messages, {len(options)} pointer fields")
